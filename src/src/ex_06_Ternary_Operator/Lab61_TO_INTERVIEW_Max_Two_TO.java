package src.ex_06_Ternary_Operator;

public class Lab61_TO_INTERVIEW_Max_Two_TO {

    static void main(String[] args) {

        // Question: Find the maximum number between two numbers.

        int x = 10;
        int y = 20;
        System.out.println(Math.max(x,y));

        // OR

        int max = x>y ? x : y;
        System.out.println(max);

    }
}
